-- พบ 2 จุดตอนอ่าน upload_screen.dart / edit_dog_screen.dart / demo_seed.dart
-- ละเอียด ซึ่งตอนออกแบบ migration 003/001 ตามแค่ entity ใน SKILL.md ยังไม่รู้:
--
-- 1. "age" เป็นข้อความอิสระ ไม่ใช่ตัวเลขเดือนล้วน
--    ageOptions ในฟอร์มสร้างประกาศ generate "1 ปี".."25 ปี" ก็จริง แต่หน้าแก้ไข
--    (edit_dog_screen.dart) ใช้ TextField ธรรมดาไม่มีตัวเลือก พิมพ์อะไรก็ได้
--    และ demo_seed.dart มีค่าเช่น "8 เดือน", "1 ปี 3 เดือน" อยู่จริง —
--    แปลงเป็น age_months (int) แบบ lossless ไม่ได้เสมอไป
--
--    เพิ่ม age_label เป็นแหล่งความจริงสำหรับแสดงผล (ตรงกับที่ frontend ส่งมา
--    เป๊ะ ๆ) ส่วน age_months ยังเก็บไว้เป็น "ตัวเลขที่ประมาณได้" (nullable)
--    ใช้กรองช่วงอายุแบบคร่าว ๆ เท่านั้น ไม่ใช่แหล่งความจริง
--
-- 2. "สถานะ" มี 4 ค่าจริง ไม่ใช่ 3
--    upload_screen.dart ให้เจ้าของเลือกได้ 3 อัน: ยังไม่ถูกรับเลี้ยง / ถูกรับเลี้ยงแล้ว
--    / ยกเลิกประกาศ — แต่ pet_status เดิม (migration 001) มีแค่
--    available/pending/adopted ไม่มีค่าที่ตรงกับ "ยกเลิกประกาศ" เลย
--
--    เพิ่มค่า enum ใหม่ 'cancelled' — Postgres เพิ่มค่า enum ได้แต่ลบไม่ได้
--    (เหตุผลเดียวกับที่ traits ไม่ใช้ enum) แต่ตรงนี้ยอมรับได้เพราะสถานะ
--    ประกาศเป็นชุดค่าที่นิ่งจริง ๆ ไม่ใช่ของที่แอดมินต้องแก้บ่อยแบบ traits
-- =============================================================================

BEGIN;

ALTER TABLE pets ADD COLUMN age_label varchar(50);

COMMENT ON COLUMN pets.age_label IS
  'ข้อความอายุตามที่ frontend ส่งมาเป๊ะ ๆ (เช่น "1 ปี 3 เดือน") — แหล่งความจริงสำหรับแสดงผล';
COMMENT ON COLUMN pets.age_months IS
  'ประมาณจาก age_label แบบ best-effort ใช้กรองช่วงอายุคร่าว ๆ เท่านั้น ไม่ใช่แหล่งความจริง';

COMMIT;

-- ALTER TYPE ... ADD VALUE ต้อง commit ก่อนถึงจะใช้ค่าใหม่ได้ในธุรกรรมอื่น
-- จึงแยกเป็นคนละ BEGIN/COMMIT จากด้านบน (แต่ไฟล์เดียวกันไม่มีปัญหา เพราะ
-- ไม่มีการ "ใช้" ค่า cancelled ในไฟล์นี้เลย)
BEGIN;

ALTER TYPE pet_status ADD VALUE IF NOT EXISTS 'cancelled';

COMMIT;
