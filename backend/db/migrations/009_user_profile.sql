-- =============================================================================
-- 009 — ข้อมูลโปรไฟล์เพิ่มเติมที่หน้าจอ Flutter เก็บอยู่จริง
--
-- ตารางในไฟล์นี้: user_contacts, user_traits (+ คอลัมน์ users.home_type)
--
-- ที่มา: ตาราง users เดิม (migration 002) สร้างตาม entity ใน SKILL.md ตรง ๆ
-- (email, password_hash, display_name, avatar_url, bio, location) แต่หน้าจอ
-- สร้างโปรไฟล์/แก้โปรไฟล์ของแอปจริงเก็บมากกว่านั้น: เบอร์โทร, LINE ID,
-- ชื่อ Facebook, ประเภทที่พักอาศัย, และนิสัย/ไลฟ์สไตล์ของผู้ใช้ (จับคู่กับ
-- แท็กของสัตว์ตอนจัดฟีด) — ถ้าไม่เพิ่มตารางเหล่านี้ กดบันทึกโปรไฟล์แล้ว
-- ข้อมูลพวกนี้จะหายไปเงียบ ๆ เพราะ DB ไม่มีที่เก็บ
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- users.home_type — ประเภทที่พักอาศัย
--
-- อยู่ตรง ๆ บน users แทนที่จะแยกตาราง เพราะเป็นค่าเดียวต่อคน (ไม่ใช่ 1-ต่อ-กี่)
-- และไม่ใช่ข้อมูลอ่อนไหวเหมือนเบอร์โทร/LINE จึงไม่จำเป็นต้องแยกสิทธิ์การอ่าน
-- ใช้ enum ไม่ใช่ text เพราะชุดตัวเลือกนิ่ง (ตรงกับ homeTypes ใน mock_data.dart)
-- -----------------------------------------------------------------------------
CREATE TYPE home_type AS ENUM (
  'detached_house',   -- บ้านเดี่ยว
  'townhouse',         -- ทาวน์โฮม/ทาวน์เฮ้าส์
  'condo',             -- คอนโดมิเนียม
  'apartment'          -- อพาร์ทเม้นท์/ห้องเช่า
);

ALTER TABLE users ADD COLUMN home_type home_type;

COMMENT ON COLUMN users.home_type IS
  'ประเภทที่พักอาศัย ใช้เป็นข้อมูลเสริมคัดกรองผู้เลี้ยง ไม่บังคับกรอก';


-- -----------------------------------------------------------------------------
-- user_contacts — ข้อมูลติดต่อส่วนตัว (เบอร์โทร / LINE / Facebook)
--
-- แยกออกจาก users เป็นตารางต่างหาก (ไม่ใช่แค่เพิ่มคอลัมน์) เพราะ:
--
--   1. สิทธิ์การอ่านต่างจากฟิลด์อื่นบน users โดยสิ้นเชิง — bio/avatar/location
--      ใครก็ดูได้ (โชว์บนโปรไฟล์สาธารณะ, ใช้ประกอบ deck_feed) แต่เบอร์โทร/LINE
--      ต้องเห็นเฉพาะเจ้าของบัญชีเท่านั้น แยกตารางทำให้เขียน authorization
--      guard ได้ตรงจุด ("query ตารางนี้ได้เฉพาะ WHERE user_id = req.user.id")
--      โดยไม่ต้องมานั่งกรอง field ออกจาก response ของ GET /users/:id ทุกครั้ง
--      ซึ่งเสี่ยงลืมกรองสักจุดแล้วข้อมูลหลุด
--
--   2. คนละอัตราการเปลี่ยนแปลง — โปรไฟล์สาธารณะแทบไม่เปลี่ยน ข้อมูลติดต่อ
--      เปลี่ยนบ่อยกว่า (เปลี่ยนเบอร์ เปลี่ยน LINE ID)
--
-- ใช้ user_id เป็น primary key ตรง ๆ (ไม่มี id แยก) เพราะเป็นความสัมพันธ์
-- 1-ต่อ-1 กับ users เป๊ะ ๆ — 1 คนมีข้อมูลติดต่อได้ชุดเดียวเท่านั้น
-- -----------------------------------------------------------------------------
CREATE TABLE user_contacts (
  user_id    uuid        PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,

  phone      varchar(20),
  line_id    varchar(50),
  fb_name    varchar(100),

  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TRIGGER user_contacts_set_updated_at
  BEFORE UPDATE ON user_contacts
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE user_contacts IS
  'ข้อมูลติดต่อส่วนตัว — อ่านได้เฉพาะเจ้าของบัญชี ห้าม join เข้า response สาธารณะ';


-- -----------------------------------------------------------------------------
-- user_traits — นิสัย/ไลฟ์สไตล์ของ "ผู้ใช้" (คนละชุดกับ pet_traits)
--
-- ใช้ตาราง traits ชุดเดียวกับที่สัตว์ใช้ (migration 007) เพราะแอปให้ผู้ใช้
-- เลือกนิสัยของตัวเองจากรายการเดียวกับที่สัตว์ติดแท็ก เพื่อให้จัดฟีดแบบ
-- "จับคู่นิสัยที่ตรงกัน" ได้ในอนาคต (เช่น คนที่เลือก "รักความสงบ" เจอสัตว์
-- ที่แท็ก "รักความสงบ" ก่อน) — ยังไม่ได้ทำ endpoint หรือ deck_feed รองรับ
-- ตอนนี้ มีแค่ที่เก็บข้อมูลให้ฟอร์มในหน้าโปรไฟล์ที่มีอยู่แล้วบันทึกได้จริง
--
-- โครงสร้างเหมือน pet_traits เป๊ะ (composite PK) ด้วยเหตุผลเดียวกัน
-- -----------------------------------------------------------------------------
CREATE TABLE user_traits (
  user_id  uuid NOT NULL REFERENCES users(id)  ON DELETE CASCADE,
  trait_id uuid NOT NULL REFERENCES traits(id) ON DELETE RESTRICT,

  PRIMARY KEY (user_id, trait_id)
);

CREATE INDEX user_traits_trait_idx ON user_traits (trait_id);

COMMENT ON TABLE user_traits IS
  'นิสัย/ไลฟ์สไตล์ที่ผู้ใช้เลือกให้ตัวเอง ใช้ชุดแท็กเดียวกับ pet_traits เพื่อจับคู่กันได้';

COMMIT;
